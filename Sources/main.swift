// cleanpaste: strips tracking parameters from a URL as soon as it lands on the clipboard.
//
// macOS has no "clipboard changed" notification, so watching means polling the
// pasteboard's change counter. Reading the counter is a round trip to the system
// pasteboard service (about 20 microseconds), so it is only done when a copy could have
// happened. The clipboard's contents are read only after the counter moves.

import AppKit

// Tuning. A copy is cleaned within `activeInterval + activeLeeway` while you are using
// the Mac. With no keyboard or mouse input for `idleAfter` seconds the poll slows down.
let activeInterval: DispatchTimeInterval = .milliseconds(200)
let activeLeeway: DispatchTimeInterval = .milliseconds(50)
let idleInterval: DispatchTimeInterval = .seconds(1)
let idleLeeway: DispatchTimeInterval = .milliseconds(500)
let idleAfter: CFTimeInterval = 60

// A copy takes a key press or a click, and "time since the last input" is a free
// shared-memory read. So the change counter is queried on every tick only within
// `recentInput` seconds of input. Otherwise it is queried every `quietQueryEvery` ticks,
// which still catches copies made by scripts or arriving from an iPhone.
let recentInput: CFTimeInterval = 2
let quietQueryEvery = 5

// Every `upgradeCheckEvery` ticks (10 s in use, 50 s idle) the agent checks whether its
// launch path now resolves to a different file, which is what `brew upgrade` does. If so it
// exits with an error, and launchd starts the new version.
let upgradeCheckEvery = 50

/// Markers that password managers and text expanders put on copies that must be left alone.
let untouchableTypes: Set<String> = [
    "org.nspasteboard.ConcealedType",
    "org.nspasteboard.TransientType",
    "org.nspasteboard.AutoGeneratedType",
    "com.agilebits.onepassword",
    "de.petermaurer.TransientPasteboardType",
    "Pasteboard generator type",
]

/// The file a path points to once symlinks are resolved, or nil if it is gone.
func resolvedPath(_ path: String) -> String? {
    guard let resolved = realpath(path, nil) else { return nil }
    defer { free(resolved) }
    return String(cString: resolved)
}

let urlNameType = NSPasteboard.PasteboardType("public.url-name")

final class Watcher {
    private let pasteboard: NSPasteboard
    // Default priority on purpose: a tick costs tens of microseconds either way, and on a
    // heavily loaded Mac .utility made ticks up to 170 ms late.
    private let queue = DispatchQueue(label: "cleanpaste.poll", qos: .default)
    private let timer: DispatchSourceTimer
    private var lastChange: Int
    private var idle = false
    /// Tries left for the current copy. An app bumps the change counter first and writes
    /// the data a moment later, so a poll that lands in between gets one retry.
    private var attemptsLeft = 0
    /// Starts full so the first tick queries the clipboard straight away.
    private var ticksSinceQuery = quietQueryEvery
    private var ticksSinceUpgradeCheck = 0
    private let launchPath = CommandLine.arguments[0]
    private lazy var runningBinary = resolvedPath(launchPath)
    private let anyInput = CGEventType(rawValue: ~0)!

    init(pasteboard: NSPasteboard) {
        self.pasteboard = pasteboard
        // No baseline: whatever is on the clipboard at launch counts as a new copy, so a
        // link copied while the agent was starting (at login, after an upgrade) is cleaned.
        lastChange = -1
        timer = DispatchSource.makeTimerSource(queue: queue)
    }

    func start() {
        _ = runningBinary
        // Pay the one-time setup costs now instead of on the first copy.
        _ = cleanURL("https://example.com/?utm_source=warmup")
        _ = pasteboard.types
        timer.setEventHandler { [unowned self] in tick() }
        setRate()
        timer.resume()
    }

    private func setRate() {
        let interval = idle ? idleInterval : activeInterval
        timer.schedule(deadline: .now() + interval, repeating: interval,
                       leeway: idle ? idleLeeway : activeLeeway)
    }

    private func tick() {
        let sinceInput = CGEventSource.secondsSinceLastEventType(.combinedSessionState,
                                                                 eventType: anyInput)
        ticksSinceQuery += 1
        if idle || sinceInput < recentInput || ticksSinceQuery >= quietQueryEvery || attemptsLeft > 0 {
            ticksSinceQuery = 0
            queryClipboard()
        }
        ticksSinceUpgradeCheck += 1
        if ticksSinceUpgradeCheck >= upgradeCheckEvery {
            ticksSinceUpgradeCheck = 0
            if resolvedPath(launchPath) != runningBinary { exit(1) }
        }
        let quiet = sinceInput > idleAfter
        if quiet != idle {
            idle = quiet
            setRate()
        }
    }

    private func queryClipboard() {
        let change = pasteboard.changeCount
        if change != lastChange {
            lastChange = change
            attemptsLeft = 2
        }
        if attemptsLeft > 0 {
            attemptsLeft -= 1
            switch autoreleasepool(invoking: { cleanClipboard(at: change) }) {
            case .retry: break
            case .done: attemptsLeft = 0
            // A copy that lands within a millisecond of our own write can share its change
            // count, so it would look like ours and be skipped. Read the clipboard once more
            // on the next tick: our own clean link is left alone, anything else gets cleaned.
            case .rewrote: attemptsLeft = 1
            }
        }
    }

    private enum Outcome { case retry, done, rewrote }

    /// `.retry` when the copy's data has not arrived yet, `.rewrote` when the clipboard was
    /// cleaned, `.done` otherwise.
    private func cleanClipboard(at change: Int) -> Outcome {
        guard let types = pasteboard.types, !types.isEmpty else { return .retry }
        guard types.contains(.string),
              !types.contains(where: { untouchableTypes.contains($0.rawValue) })
        else { return .done }
        guard let text = pasteboard.string(forType: .string) else { return .retry }
        guard let cleaned = cleanURL(text) else { return .done }

        // Carry over the link title if the copy had one, then replace everything else:
        // the other representations (HTML, RTF, URL) all still hold the tracked URL.
        let title = types.contains(urlNameType) ? pasteboard.string(forType: urlNameType) : nil

        // Something else was copied while we were working: leave it for the next tick.
        guard pasteboard.changeCount == change else { return .done }

        // clearContents + setString is the fastest pair of calls (about 10x quicker than
        // declareTypes), which keeps the moment the clipboard is empty as short as possible.
        lastChange = pasteboard.clearContents()
        pasteboard.setString(cleaned, forType: .string)
        if types.contains(.URL) { pasteboard.setString(cleaned, forType: .URL) }
        if let title { pasteboard.setString(title, forType: urlNameType) }
        return .rewrote
    }
}

let watcher = Watcher(pasteboard: .general)
watcher.start()
dispatchMain()
